# Characters drawn as another glyph plus an accent above the cell.
_ACCENTED = {"Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U", "Ñ": "N", "Ü": "U"}
_MARKS = {
    "acute": [(2, -2), (3, -3)],
    "tilde": [(0, -2), (1, -3), (2, -2), (3, -2), (4, -3)],
    "dieresis": [(1, -2), (3, -2)],
}
_MARK_OF = {"Á": "acute", "É": "acute", "Í": "acute", "Ó": "acute", "Ú": "acute",
            "Ñ": "tilde", "Ü": "dieresis"}
_ALIASES = {"★": "*", "—": "-", "–": "-", "•": "·", "|": "!"}

WIDTH, HEIGHT = 5, 7


def _cells(ch: str) -> list[tuple[int, int]]:
    ch = _ALIASES.get(ch, ch)
    base = _ACCENTED.get(ch, ch)
    rows = _RAW.get(base, _RAW["?"])
    cells = [(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"]
    if ch in _MARK_OF:
        cells += _MARKS[_MARK_OF[ch]]
    return cells


def layout(text: str, spacing: int = 1) -> tuple[list[tuple[int, int]], int]:
    """Return lit cells (x, y) in font units and the total advance width."""
    cells: list[tuple[int, int]] = []
    x = 0
    for ch in text.upper():
        cells.extend((x + cx, cy) for cx, cy in _cells(ch))
        x += WIDTH + spacing
    return cells, max(0, x - spacing)


def text_width(text: str, scale: float, spacing: int = 1) -> float:
    return layout(text, spacing)[1] * scale


def path(text: str, x: float, y: float, scale: float, spacing: int = 1) -> str:
    """SVG path data for `text` with its top-left corner at (x, y).

    Horizontal runs of lit pixels are merged into one rectangle each, which
    keeps long strings (like the scrolling marquee) small.
    """
    cells, _ = layout(text, spacing)
    rows: dict[int, list[int]] = {}
    for cx, cy in cells:
        rows.setdefault(cy, []).append(cx)
    out = []
    for cy, xs in sorted(rows.items()):
        xs = sorted(set(xs))
        start = prev = xs[0]
        for cx in xs[1:] + [None]:
            if cx is not None and cx == prev + 1:
                prev = cx
                continue
            w = (prev - start + 1) * scale
            out.append(f"M{_n(x + start * scale)} {_n(y + cy * scale)}h{_n(w)}v{_n(scale)}h{_n(-w)}z")
            if cx is not None:
                start = prev = cx
    return "".join(out)


def _n(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")
